// Runs before `next dev` and `next build` (predev / prebuild).
// Detects the optional hero reels and enforces their size budgets, so components never touch the
// file system at render time and phones never download a heavy reel.
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(root, 'src', 'generated', 'media.ts');
const MB = 1024 * 1024;

// Budgets from the brief: desktop ≤ 4 MB, mobile ≤ 2.5 MB (small tolerance for container overhead).
const BUDGET = { desktop: 4 * MB, mobile: 2.5 * MB };
const HARD_LIMIT = { desktop: 6 * MB, mobile: 2.6 * MB };

function reel(kind, path) {
  const abs = join(root, 'public', path);
  if (!existsSync(abs)) return null;
  const size = statSync(abs).size;
  const mb = (size / MB).toFixed(2);
  if (size > HARD_LIMIT[kind]) {
    console.warn(`! ${path} is ${mb} MB (budget ${(BUDGET[kind] / MB).toFixed(1)} MB): not used. Compress it (see README).`);
    return null;
  }
  if (size > BUDGET[kind]) console.warn(`! ${path} is ${mb} MB, over the ${(BUDGET[kind] / MB).toFixed(1)} MB budget. Consider re-encoding.`);
  return `/${path}`;
}

const desktop = reel('desktop', 'videos/hero-reel.mp4');
// Phones never fall back to the (heavier, 16:9) desktop reel: they get the still unless a light mobile reel exists.
const mobile = reel('mobile', 'videos/hero-reel-mobile.mp4');

const ts = `// AUTO-GENERATED by scripts/media-manifest.mjs (runs before dev and build). Do not edit by hand.
export const heroReel: { desktop: string | null; mobile: string | null } = ${JSON.stringify({ desktop, mobile })};
`;

mkdirSync(dirname(file), { recursive: true });
if (!existsSync(file) || readFileSync(file, 'utf8') !== ts) writeFileSync(file, ts);
console.log(`Hero reel: desktop=${desktop ?? 'none'} mobile=${mobile ?? 'none'}`);
