// Runs before `next dev` and `next build` (predev / prebuild).
// Detects the optional hero reel so components never touch the file system at render time.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(root, 'src', 'generated', 'media.ts');
const has = (p) => existsSync(join(root, 'public', p));

const desktop = has('videos/hero-reel.mp4') ? '/videos/hero-reel.mp4' : null;
// Phones never fall back to the (heavier, 16:9) desktop reel: they get the still unless a mobile reel exists.
const mobile = has('videos/hero-reel-mobile.mp4') ? '/videos/hero-reel-mobile.mp4' : null;

const ts = `// AUTO-GENERATED by scripts/media-manifest.mjs (runs before dev and build). Do not edit by hand.
export const heroReel: { desktop: string | null; mobile: string | null } = ${JSON.stringify({ desktop, mobile })};
`;

mkdirSync(dirname(file), { recursive: true });
if (!existsSync(file) || readFileSync(file, 'utf8') !== ts) writeFileSync(file, ts);
console.log(`Hero reel: desktop=${desktop ?? 'none'} mobile=${mobile ?? 'none'}`);
